const normalize = (value: string) => value.toLowerCase().replace(/\s+/g, "");

/** 상품명·규격으로 카테고리를 추천합니다. 못 찾으면 빈 값. 앞쪽 규칙(냉동·수산·정육…)이 우선입니다. */
export function suggestCategory(name: string, spec = ""): string {
  const text = normalize(`${name} ${spec}`);
  if (!text) return "";
  for (const [category, words] of RULES) {
    if (words.some((word) => text.includes(normalize(word)))) return category;
  }
  return "";
}

/** 기본 목록 + 이미 쓰고 있는 카테고리(사용자가 만든 것)를 합쳐 고를 수 있는 목록을 만듭니다. */
export function categoryOptions(existing: readonly string[]) {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const value of [...DEFAULT_CATEGORIES, ...existing]) {
    const name = value.trim();
    if (name && !seen.has(name)) { seen.add(name); out.push(name); }
  }
  return out;
}

export function cleanCategory(value: unknown): string | null | { error: string } {
  if (value === null) return null;
  if (typeof value !== "string") return { error: "카테고리를 확인해 주세요." };
  const name = value.trim();
  if (!name) return null;
  if (name.length > 30) return { error: "카테고리 이름은 30자까지입니다." };
  return name;
}
